#pragma once
#include <vector>
#include <DirectXMath.h>
#include "Components/Components.h" 

using namespace DirectX;

/***
* @brief 定型的な形状(ジオメトリ)を生成するクラス
*/
class GeometoryGenerator {
public:
    /**
    * @brief 立方体の頂点データを生成します
    * @param size 一辺の長さ
    * @return 生成された頂点データのリスト
    */
    static std::vector<Vertex> CreateCube(float size = 1.0f)
    {
        float h = size / 2.0f;

        // 頂点データ：{ x, y, z,  r, g, b, a,  nx, ny, nz } の10個をセットにします
        std::vector<Vertex> vertices =
        {
            // 前面 (Z = -h) 法線は手前向き(0,0,-1)
            { -h,  h, -h,  1.0f, 1.0f, 1.0f, 1.0f,  0.0f, 0.0f, -1.0f }, {  h,  h, -h,  1.0f, 1.0f, 1.0f, 1.0f,  0.0f, 0.0f, -1.0f }, {  h, -h, -h,  1.0f, 1.0f, 1.0f, 1.0f,  0.0f, 0.0f, -1.0f },
            { -h,  h, -h,  1.0f, 1.0f, 1.0f, 1.0f,  0.0f, 0.0f, -1.0f }, {  h, -h, -h,  1.0f, 1.0f, 1.0f, 1.0f,  0.0f, 0.0f, -1.0f }, { -h, -h, -h,  1.0f, 1.0f, 1.0f, 1.0f,  0.0f, 0.0f, -1.0f },
            // 背面 (Z = h) 法線は奥向き(0,0,1)
            {  h,  h,  h,  1.0f, 1.0f, 1.0f, 1.0f,  0.0f, 0.0f, 1.0f }, { -h,  h,  h,  1.0f, 1.0f, 1.0f, 1.0f,  0.0f, 0.0f, 1.0f }, { -h, -h,  h,  1.0f, 1.0f, 1.0f, 1.0f,  0.0f, 0.0f, 1.0f },
            {  h,  h,  h,  1.0f, 1.0f, 1.0f, 1.0f,  0.0f, 0.0f, 1.0f }, { -h, -h,  h,  1.0f, 1.0f, 1.0f, 1.0f,  0.0f, 0.0f, 1.0f }, {  h, -h,  h,  1.0f, 1.0f, 1.0f, 1.0f,  0.0f, 0.0f, 1.0f },
            // 上面 (Y = h) 法線は上向き(0,1,0)
            { -h,  h,  h,  1.0f, 1.0f, 1.0f, 1.0f,  0.0f, 1.0f, 0.0f }, {  h,  h,  h,  1.0f, 1.0f, 1.0f, 1.0f,  0.0f, 1.0f, 0.0f }, {  h,  h, -h,  1.0f, 1.0f, 1.0f, 1.0f,  0.0f, 1.0f, 0.0f },
            { -h,  h,  h,  1.0f, 1.0f, 1.0f, 1.0f,  0.0f, 1.0f, 0.0f }, {  h,  h, -h,  1.0f, 1.0f, 1.0f, 1.0f,  0.0f, 1.0f, 0.0f }, { -h,  h, -h,  1.0f, 1.0f, 1.0f, 1.0f,  0.0f, 1.0f, 0.0f },
            // 下面 (Y = -h) 法線は下向き(0,-1,0)
            { -h, -h, -h,  1.0f, 1.0f, 1.0f, 1.0f,  0.0f, -1.0f, 0.0f }, {  h, -h, -h,  1.0f, 1.0f, 1.0f, 1.0f,  0.0f, -1.0f, 0.0f }, {  h, -h,  h,  1.0f, 1.0f, 1.0f, 1.0f,  0.0f, -1.0f, 0.0f },
            { -h, -h, -h,  1.0f, 1.0f, 1.0f, 1.0f,  0.0f, -1.0f, 0.0f }, {  h, -h,  h,  1.0f, 1.0f, 1.0f, 1.0f,  0.0f, -1.0f, 0.0f }, { -h, -h,  h,  1.0f, 1.0f, 1.0f, 1.0f,  0.0f, -1.0f, 0.0f },
            // 左面 (X = -h) 法線は左向き(-1,0,0)
            { -h,  h,  h,  1.0f, 1.0f, 1.0f, 1.0f, -1.0f, 0.0f, 0.0f }, { -h,  h, -h,  1.0f, 1.0f, 1.0f, 1.0f, -1.0f, 0.0f, 0.0f }, { -h, -h, -h,  1.0f, 1.0f, 1.0f, 1.0f, -1.0f, 0.0f, 0.0f },
            { -h,  h,  h,  1.0f, 1.0f, 1.0f, 1.0f, -1.0f, 0.0f, 0.0f }, { -h, -h, -h,  1.0f, 1.0f, 1.0f, 1.0f, -1.0f, 0.0f, 0.0f }, { -h, -h,  h,  1.0f, 1.0f, 1.0f, 1.0f, -1.0f, 0.0f, 0.0f },
            // 右面 (X = h) 法線は右向き(1,0,0)
            {  h,  h, -h,  1.0f, 1.0f, 1.0f, 1.0f,  1.0f, 0.0f, 0.0f }, {  h,  h,  h,  1.0f, 1.0f, 1.0f, 1.0f,  1.0f, 0.0f, 0.0f }, {  h, -h,  h,  1.0f, 1.0f, 1.0f, 1.0f,  1.0f, 0.0f, 0.0f },
            {  h,  h, -h,  1.0f, 1.0f, 1.0f, 1.0f,  1.0f, 0.0f, 0.0f }, {  h, -h,  h,  1.0f, 1.0f, 1.0f, 1.0f,  1.0f, 0.0f, 0.0f }, {  h, -h, -h,  1.0f, 1.0f, 1.0f, 1.0f,  1.0f, 0.0f, 0.0f },
        };
        return vertices;
    }
};